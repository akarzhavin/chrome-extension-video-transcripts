// Turn a raw #vtt-export dump into src/data/demo-subs.json.
//
//   node apps/site/scripts/import-demo-subs.mjs \
//       apps/site/data-src/demo-subs-Kk1vR7BdTno.json --end 101.46
//
// The raw dump is kept in data-src/ so the demo can be rebuilt without going
// back to YouTube. `--end` trims the loop window: the ASR track runs past the
// last spoken line into the music tail.
//
// The export carries every track YouTube offers for the video — the author's
// own, the ASR one, and a machine translation per supported language. The demo
// keeps the author's track plus one translation per language, keyed by the
// language code so the page can pick the visitor's own. Track names come from
// SUPPORTED_LANGUAGES.label, which is what the sidebar matches on.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/data/demo-subs.json');

// Mirrors packages/shared/src/languages.ts. Duplicated rather than imported:
// this script runs on plain Node against TypeScript sources it can't load.
const LABELS = {
    en: 'English', es: 'Spanish', pt: 'Portuguese', fr: 'French', de: 'German',
    it: 'Italian', nl: 'Dutch', ru: 'Russian', uk: 'Ukrainian', pl: 'Polish',
    cs: 'Czech', sk: 'Slovak', bg: 'Bulgarian', sr: 'Serbian', hr: 'Croatian',
    sl: 'Slovenian', ro: 'Romanian', hu: 'Hungarian', el: 'Greek', tr: 'Turkish',
    sv: 'Swedish', no: 'Norwegian', da: 'Danish', fi: 'Finnish', et: 'Estonian',
    lv: 'Latvian', lt: 'Lithuanian', ar: 'Arabic', he: 'Hebrew', fa: 'Persian',
    hi: 'Hindi', bn: 'Bengali', ta: 'Tamil', te: 'Telugu', th: 'Thai',
    vi: 'Vietnamese', id: 'Indonesian', ms: 'Malay', fil: 'Filipino',
    ja: 'Japanese', ko: 'Korean', zh: 'Chinese',
};

const src = process.argv[2];
if (!src) {
    console.error('usage: import-demo-subs.mjs <exported.json> [--end <seconds>]');
    process.exit(1);
}
const endFlag = process.argv.indexOf('--end');
const raw = JSON.parse(readFileSync(src, 'utf8'));

// One track per language: the video's own beats a machine translation, and a
// real track beats the ASR one.
const rank = (t) => (t.translated ? 2 : t.kind === 'asr' ? 1 : 0);
const best = new Map();
for (const track of raw.tracks) {
    const code = (track.lang || '').split(/[-_]/)[0].toLowerCase();
    if (!LABELS[code] || !track.lines?.length) continue;
    const seen = best.get(code);
    if (!seen || rank(track) < rank(seen)) best.set(code, track);
}

const codes = [...best.keys()].sort((a, b) =>
    a === 'en' ? -1 : b === 'en' ? 1 : LABELS[a].localeCompare(LABELS[b]),
);

const lines = [...best.values()].flatMap((t) => t.lines);
const windowEnd =
    endFlag > 0 ? Number(process.argv[endFlag + 1]) : Math.max(...lines.map((l) => l.endTime));

const out = {
    _comment:
        'Hero-demo subtitles, generated by apps/site/scripts/import-demo-subs.mjs from an extension export (#vtt-export). English is the video\'s own caption track; every other language is YouTube\'s machine translation of it — exactly what the extension shows a viewer whose language has no native track. Keyed by language code so the page can open on the visitor\'s own. Source: NASA "Cosmic Dawn" trailer — public domain. Do not hand-edit; re-run the script.',
    youtubeVideoId: raw.youtubeVideoId,
    windowStart: raw.windowStart ?? 0,
    windowEnd: Math.round(windowEnd * 100) / 100,
    tracks: codes.map((code) => ({
        lang: code,
        name: LABELS[code],
        lines: best.get(code).lines,
    })),
};

writeFileSync(OUT, JSON.stringify(out) + '\n');
console.log(
    `${out.tracks.length} tracks → ${OUT} (${Math.round(JSON.stringify(out).length / 1024)} KB)`,
);
