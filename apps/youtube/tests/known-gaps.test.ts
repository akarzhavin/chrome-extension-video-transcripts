describe('anonymous measurements cannot be traced to a person', () => {
    /**
     * Behaviour map §34. Because nothing identifying is attached, a request to
     * delete "my" measurements cannot be honoured — there is nothing to look
     * up. That is a real limitation, and it is also the thing that makes the
     * measurements genuinely anonymous.
     *
     * This pins the mechanical guard rather than the promise: a list of names
     * that must never reach a payload, so one careless spread breaks a check
     * instead of the privacy policy.
     */
    test('identifying names are refused mechanically, not by discipline', () => {
        const analytics = sharedRead('/src/analytics.ts');
        for (const denied of ['uid', 'email', 'id_token', 'refresh_token']) {
            expect(analytics).toMatch(new RegExp(`'${denied}'`));
        }
        // The saved word and the line it came from are content, never telemetry.
        for (const denied of ['term', 'context', 'text']) {
            expect(analytics).toMatch(new RegExp(`'${denied}'`));
        }
    });
});

