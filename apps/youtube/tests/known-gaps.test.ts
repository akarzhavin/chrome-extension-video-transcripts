describe('announcements from the product team', () => {
    /**
     * Behaviour map §22. A message arrives from a server, so one cannot be
     * summoned on demand without standing up test content — the live checks
     * therefore do not cover it.
     *
     * What can be pinned without a server is the contract that matters most:
     * a dismissed message must never come back. That is stored, and the
     * storage is what a returning message would have to get past.
     */
    test('a dismissed message is remembered, and failures are silent by design', () => {
        const notifications = sharedRead('/src/notifications.ts');

        // Dismissals are kept, which is what stops a message returning.
        expect(notifications).toMatch(/notif\.dismissed/);

        // The list is pruned once a message is gone, so it cannot grow for the
        // life of the installation.
        expect(notifications).toMatch(/pruneDismissals/);

        // Nothing about this is ever shown as an error: a message that cannot
        // be fetched simply does not appear. Worth knowing, because it means
        // "no message today" and "the server is unreachable" look identical to
        // everyone, including us.
        expect(notifications).toMatch(/catch/);
        expect(notifications).not.toMatch(/throw new Error/);
    });
});

describe('Netflix support and what the documents say about it', () => {
    /**
     * Behaviour map §36, and the map's wording needed correcting: the extension
     * does NOT run on Netflix "without saying so". The store listing names
     * Netflix in both its title and its description.
     *
     * The real gap is narrower and is in the privacy policy: it introduces
     * itself as covering two editions, HDrezka and YouTube, and describes the
     * saved-word source tag as "HDrezka or YouTube" — while the same extension
     * runs on Netflix and labels data `netflix`.
     *
     * A reader checking whether the policy covers the Netflix they were
     * promised on the storefront finds the platform named once, in a list of
     * label values, and nowhere in the description of what the product is.
     */
    test('the policy names Netflix where the storefront promises it', () => {
        const listing = JSON.parse(
            readFileSync(join(__dirname, '..', '_locales', 'en', 'messages.json'), 'utf8'),
        );
        const policy = readFileSync(join(__dirname, '..', '..', '..', 'PRIVACY_POLICY.md'), 'utf8');

        // The storefront is explicit.
        expect(listing.appName.message).toMatch(/Netflix/);
        expect(listing.appDesc.message).toMatch(/Netflix/);

        // So the policy must be too, where it introduces what it covers — not
        // only as one value in a list of platform labels.
        const editionsBlock = policy.slice(0, policy.indexOf('## TL;DR'));
        expect(editionsBlock).toMatch(/Netflix/i);

        // And in the source tag a saved word carries.
        expect(policy).toMatch(/`netflix`/);
    });

    test('Netflix runs inside this extension rather than an edition of its own', () => {
        // Which is why nobody installing "for YouTube" would think to look for a
        // separate listing — and why the policy naming two editions leaves the
        // third surface undescribed.
        const manifest = JSON.parse(readFileSync(join(__dirname, '..', 'manifest.json'), 'utf8'));
        const matches = JSON.stringify(manifest.content_scripts);
        expect(matches).toMatch(/netflix\.com/);
        expect(matches).toMatch(/youtube\.com/);
    });
});

/**
 * §34.3, T5.31 — the policy says the measurements cannot be deleted.
 *
 * Not a known gap: a stated fact about the product, and the one the analytics
 * design turns on. The events carry no account identifier, which is what makes
 * them anonymous — and the price of that is that nobody, the developer
 * included, can find a given person's events to remove them. A policy that
 * promised deletion here would be promising something the architecture cannot
 * do, which is the shape of a data-safety rejection.
 *
 * A document pin: red is obtained by editing PRIVACY_POLICY.md, not the code.
 */
describe('the policy states that measurements cannot be deleted', () => {
    const policy = (): string =>
        readFileSync(join(__dirname, '..', '..', '..', 'PRIVACY_POLICY.md'), 'utf8');

    test('it says the events cannot be looked up or deleted, by either party', () => {
        expect(policy()).toMatch(
            /we cannot look up or\s*\n?\s*delete the events belonging to a specific person — and neither can you/,
        );
    });

    test('it gives the reason: the events carry no account identifier', () => {
        expect(policy()).toMatch(/these events carry no account identifier/i);
    });

    // The other half of the same paragraph, and the part a user acts on: the
    // switch stops future collection but cannot reach back. Without this, the
    // sentence above could be read as "your data is stuck here forever".
    test('it says opting out stops collection without removing what was sent', () => {
        const text = policy();
        expect(text).toMatch(/stops any further collection/i);
        expect(text).toMatch(/cannot retroactively remove/i);
        expect(text).toMatch(/2-month/);
    });
});
